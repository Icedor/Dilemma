<?php
declare(strict_types=1);
ob_start();
require __DIR__ . '/bootstrap.php';
use Dilemma\{Auth, Accounts, Config, Db, I18n, Mail, Push, Support};

$a = user_fixture('PushA'); $b = user_fixture('PushB');
$a_user = Auth::session($a['session']['token']);
$b_user = Auth::session($b['session']['token']);
$debate = debate_fixture($a['actor'], $b['actor']);
$endpoint = 'https://fcm.googleapis.com/fcm/send/test-' . $run;
check(!Push::status($a_user)['enabled'], 'Push starts disabled');
foreach (['https://127.0.0.1/x', 'https://fcm.googleapis.com.attacker.test/x', 'http://fcm.googleapis.com/x', 'https://attacker@fcm.googleapis.com/x', 'https://fcm.googleapis.com:444/x', 'https://fcm.googleapis.com/x#fragment'] as $bad) rejects(fn () => Push::endpoint($bad), 422, 'Reject non-provider or malformed endpoint');
rejects(fn () => Push::subscribe($a_user, ['endpoint' => $endpoint]), 422, 'Explicit notification consent is required');
Push::subscribe($a_user, ['endpoint' => $endpoint, 'consent' => true]);
$row = Db::one('SELECT * FROM push_subscriptions WHERE user_id = ?', [$a_user['id']]);
check($row['encrypted_endpoint'] !== $endpoint && Support::unseal($row['encrypted_endpoint']) === $endpoint, 'Device endpoint encrypted at rest');
rejects(fn () => Push::subscribe($b_user, ['endpoint' => $endpoint, 'consent' => true]), 409, 'Another account cannot claim a registered device');
$before = (int) Db::one('SELECT COUNT(*) AS n FROM notification_outbox WHERE user_id = ?', [$a_user['id']])['n'];
Mail::notify($debate['id'], $b_user['id'], 'argument', 987654321);
Mail::notify($debate['id'], $b_user['id'], 'argument', 987654321);
check((int) Db::one('SELECT COUNT(*) AS n FROM push_outbox WHERE subscription_id = ?', [$row['id']])['n'] === 1, 'Push event is queued once');
check((int) Db::one('SELECT COUNT(*) AS n FROM notification_outbox WHERE user_id = ?', [$a_user['id']])['n'] === $before + 1, 'Push queues one delayed email fallback, not duplicate messages');
$keys = Push::keys();
$header = Push::authorization('https://fcm.googleapis.com', $keys, 1700000000);
preg_match('/vapid t=([^,]+), k=/', $header, $match);
$parts = explode('.', $match[1]);
$decode = static fn (string $data): string => base64_decode(strtr($data, '-_', '+/'), true);
$claims = json_decode($decode($parts[1]), true);
check($claims['aud'] === 'https://fcm.googleapis.com' && $claims['exp'] === 1700003600, 'VAPID audience and short expiry are correct');
$signature = $decode($parts[2]);
$integer = static function (string $value): string { $value = ltrim($value, "\0"); if (ord($value[0]) > 127) $value = "\0" . $value; return "\x02" . chr(strlen($value)) . $value; };
$sequence = $integer(substr($signature, 0, 32)) . $integer(substr($signature, 32));
$der = "\x30" . chr(strlen($sequence)) . $sequence;
$public = openssl_pkey_get_details(openssl_pkey_get_private($keys['private']))['key'];
check(strlen($signature) === 64 && openssl_verify($parts[0] . '.' . $parts[1], $der, $public, OPENSSL_ALGO_SHA256) === 1, 'VAPID ES256 signature independently verifies with OpenSSL');
check(!str_contains($header, $a_user['email']) && !str_contains($header, $debate['id']), 'Push authorization contains no participant or debate content');
Push::disable($b_user);
check(Db::one('SELECT id FROM push_subscriptions WHERE id = ?', [$row['id']]) !== null, 'Disabling push cannot remove another account devices');
Auth::logout($a_user);
check(Db::one('SELECT id FROM push_subscriptions WHERE id = ?', [$row['id']]) === null && Db::one('SELECT id FROM push_outbox WHERE subscription_id = ?', [$row['id']]) === null, 'Sign-out removes session device and pending deliveries');
Push::subscribe($b_user, ['endpoint' => $endpoint, 'consent' => true]);
Push::disable($b_user);
check(!(bool) Db::one('SELECT push_enabled FROM users WHERE id = ?', [$b_user['id']])['push_enabled'], 'Explicit disable resets account preference');
check(Db::one('SELECT id FROM push_subscriptions WHERE user_id = ?', [$b_user['id']]) === null, 'Explicit disable removes all account subscriptions');
echo "SUCCESS: $checks push checks. No network delivery.\n";
